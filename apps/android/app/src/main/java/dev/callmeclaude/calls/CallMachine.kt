package dev.callmeclaude.calls

/**
 * The call protocol as a pure state machine (no Android types), ported from
 * apps/ios/CallMeClaude/CallManager.swift. [CallManager] feeds it events and carries out the
 * effects it returns; tests drive it directly.
 *
 * Directions are always from the HUB's point of view:
 *  - the hub calls us: `call.incoming {callId}` → answer → `call.start {callId, "outbound"}`
 *  - we call the hub: our own callId → `call.start {callId, "inbound"}`
 * Either way the hub replies `call.ready {callId}`. Hub messages for any other callId are ignored,
 * so a stale "ended" can never kill the live call.
 */
class CallMachine(private val clock: () -> Long) {

    enum class Direction(val wire: String) { OUTBOUND("outbound"), INBOUND("inbound") }

    enum class EndCause { LOCAL, REMOTE, REJECTED, MISSED, ERROR }

    data class ActiveCall(
        val callId: String,
        val direction: Direction,
        val title: String,
        val createdAt: Long,
        val answered: Boolean = false,
        val ready: Boolean = false,
        val connectedAt: Long? = null,
        val unreachable: Boolean = false,
    )

    sealed interface Event {
        data class Incoming(val callId: String, val title: String) : Event
        /** The user tapped "Call Claude"; [callId] is freshly generated by [newCallId]. */
        data class Place(val callId: String) : Event
        /** Telecom answered the incoming call, or created our outgoing connection. */
        data class Begin(val callId: String) : Event
        data object HubConnected : Event
        data object HubDisconnected : Event
        data class HubUnreachable(val callId: String) : Event
        data class Ready(val callId: String) : Event
        data class HubEnded(val callId: String, val reason: String) : Event
        data class HangUp(val callId: String? = null) : Event
        data class Reject(val callId: String) : Event
        /** Telecom refused the call (e.g. a cellular call is in progress). */
        data class TelecomFailed(val callId: String) : Event
        data class ReadyTimeout(val callId: String) : Event
        data class RingTimeout(val callId: String) : Event
    }

    sealed interface Effect {
        data class ReportIncoming(val callId: String, val title: String) : Effect
        data class PlaceOutgoing(val callId: String) : Effect
        data class SendStart(val callId: String, val direction: Direction) : Effect
        data class SendEnd(val callId: String) : Effect
        /** Connect if needed; report [Event.HubUnreachable] if that fails. */
        data class EnsureConnected(val callId: String) : Effect
        data object StartAudio : Effect
        data object StopAudio : Effect
        data class SetConnectionActive(val callId: String) : Effect
        data class EndConnection(val callId: String, val cause: EndCause) : Effect
        data class Schedule(val event: Event, val delayMs: Long) : Effect
        /** Say "your computer can't be reached" locally, then hang up after [UNREACHABLE_HANGUP_MS]. */
        data class Unreachable(val callId: String) : Effect
    }

    var active: ActiveCall? = null
        private set
    var linkUp = false
        private set

    /** The call was talking and the hub link dropped: the call screen says "Reconnecting…". */
    val reconnecting: Boolean
        get() = active?.let { it.answered && it.connectedAt != null && !linkUp && !it.unreachable } == true

    /** Whether `call.start` went out on the current link (reset on every disconnect). */
    private var startSentOnLink = false

    fun handle(e: Event): List<Effect> = when (e) {
        is Event.Incoming -> incoming(e)
        is Event.Place -> place(e)
        is Event.Begin -> begin(e)
        Event.HubConnected -> {
            linkUp = true
            sendStartIfNeeded()
        }
        Event.HubDisconnected -> {
            linkUp = false
            startSentOnLink = false
            emptyList()
        }
        is Event.HubUnreachable -> forActive(e.callId) { a -> if (!a.ready) unreachable(a) else emptyList() }
        is Event.ReadyTimeout -> forActive(e.callId) { a -> if (a.answered && !a.ready) unreachable(a) else emptyList() }
        is Event.Ready -> forActive(e.callId) { a ->
            if (a.ready) {
                emptyList()
            } else {
                active = a.copy(ready = true, connectedAt = clock())
                // An answered incoming call is already active in Telecom; ours becomes active now.
                if (a.direction == Direction.INBOUND) listOf(Effect.SetConnectionActive(a.callId)) else emptyList()
            }
        }
        is Event.HubEnded -> forActive(e.callId) { a ->
            cleanup(a, if (e.reason.contains("error")) EndCause.ERROR else EndCause.REMOTE)
        }
        is Event.HangUp -> {
            val a = active
            if (a == null || (e.callId != null && e.callId != a.callId)) emptyList()
            else listOf(Effect.SendEnd(a.callId)) + cleanup(a, EndCause.LOCAL)
        }
        is Event.Reject -> forActive(e.callId) { a -> listOf(Effect.SendEnd(a.callId)) + cleanup(a, EndCause.REJECTED) }
        is Event.TelecomFailed -> forActive(e.callId) { a -> cleanup(a, EndCause.ERROR, endConnection = false) }
        is Event.RingTimeout -> forActive(e.callId) { a ->
            if (a.answered) emptyList() else listOf(Effect.SendEnd(a.callId)) + cleanup(a, EndCause.MISSED)
        }
    }

    private fun incoming(e: Event.Incoming): List<Effect> {
        val a = active
        if (a != null) {
            // Same call announced again (e.g. after a reconnect): nothing to do. Busy: decline the new one.
            return if (a.callId == e.callId) emptyList() else listOf(Effect.SendEnd(e.callId))
        }
        active = ActiveCall(e.callId, Direction.OUTBOUND, e.title, clock())
        return listOf(
            Effect.ReportIncoming(e.callId, e.title),
            Effect.Schedule(Event.RingTimeout(e.callId), RING_TIMEOUT_MS),
        )
    }

    private fun place(e: Event.Place): List<Effect> {
        val out = mutableListOf<Effect>()
        val a = active
        if (a != null) {
            // Recover from a stuck call that never got answered/connected.
            if (!a.ready && clock() - a.createdAt > STUCK_MS) out += cleanup(a, EndCause.ERROR)
            else return emptyList()
        }
        active = ActiveCall(e.callId, Direction.INBOUND, "", clock())
        out += Effect.PlaceOutgoing(e.callId)
        return out
    }

    /** Answered / placed: start the mic and tell the hub to start the conversation. */
    private fun begin(e: Event.Begin): List<Effect> = forActive(e.callId) { a ->
        if (a.answered) return@forActive emptyList()
        active = a.copy(answered = true)
        val out = mutableListOf<Effect>()
        if (a.direction == Direction.OUTBOUND) out += Effect.SetConnectionActive(a.callId)
        out += Effect.StartAudio
        // Never hang on "connecting…": give up cleanly after 15 s.
        out += Effect.Schedule(Event.ReadyTimeout(a.callId), READY_TIMEOUT_MS)
        out += if (linkUp) sendStartIfNeeded() else listOf(Effect.EnsureConnected(a.callId))
        out
    }

    private fun sendStartIfNeeded(): List<Effect> {
        val a = active ?: return emptyList()
        if (!a.answered || !linkUp || startSentOnLink || a.unreachable) return emptyList()
        startSentOnLink = true
        // Idempotent on the hub: the same callId re-attaches instead of starting over.
        return listOf(Effect.SendStart(a.callId, a.direction))
    }

    private fun unreachable(a: ActiveCall): List<Effect> {
        if (a.unreachable) return emptyList()
        active = a.copy(unreachable = true)
        return listOf(
            Effect.Unreachable(a.callId),
            Effect.Schedule(Event.HangUp(a.callId), UNREACHABLE_HANGUP_MS),
        )
    }

    private fun cleanup(a: ActiveCall, cause: EndCause, endConnection: Boolean = true): List<Effect> {
        active = null
        startSentOnLink = false
        return buildList {
            if (a.answered) add(Effect.StopAudio)
            if (endConnection) add(Effect.EndConnection(a.callId, cause))
        }
    }

    private inline fun forActive(callId: String, f: (ActiveCall) -> List<Effect>): List<Effect> {
        val a = active ?: return emptyList()
        return if (a.callId == callId) f(a) else emptyList()
    }

    companion object {
        const val READY_TIMEOUT_MS = 15_000L
        /** The hub counts a call as missed after 50 s; stop ringing at the same time. */
        const val RING_TIMEOUT_MS = 50_000L
        const val STUCK_MS = 20_000L
        const val UNREACHABLE_HANGUP_MS = 6_000L

        /** "c_" + the first 8 characters of a UUID, lowercase (same as iOS). */
        fun newCallId(uuid: String = java.util.UUID.randomUUID().toString()): String = "c_" + uuid.take(8).lowercase()
    }
}
